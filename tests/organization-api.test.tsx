import { authorFetch, assertIsolatedTestEnvironment, deleteTestUsers } from "./auth-fixture";
import assert from "node:assert/strict";
import { test } from "node:test";
import { PrismaClient } from "@prisma/client";

const origin = process.env.WORLDFORGE_TEST_ORIGIN;
if (origin) assertIsolatedTestEnvironment();
test("organization API prevents cycles and cross-world moves, persists order, and preserves contents on deletion", { skip: !origin }, async context => {
  assert.match(origin!, /^http:\/\/(?:127\.0\.0\.1|localhost):\d+$/);
  const db = new PrismaClient();
  const user = await db.user.create({ data: { name: "Organization test fixture", email: `organization-${Date.now()}@example.invalid` } });
  context.after(async () => { await deleteTestUsers(db, user.id); await db.$disconnect(); });
  const authenticatedFetch = await authorFetch(db, user.id, origin!);
  const world = await db.world.create({ data: { ownerId: user.id, title: "Test world", slug: `organization-${Date.now()}` } });
  const otherWorld = await db.world.create({ data: { ownerId: user.id, title: "Other world", slug: `other-${Date.now()}` } });
  const parent = await db.category.create({ data: { worldId: world.id, name: "Atlas", order: 0 } });
  const child = await db.category.create({ data: { worldId: world.id, parentId: parent.id, name: "Cities", order: 0 } });
  const foreign = await db.category.create({ data: { worldId: otherWorld.id, name: "Foreign" } });
  const first = await db.article.create({ data: { worldId: world.id, categoryId: parent.id, title: "A", slug: "a", order: 0 } });
  const second = await db.article.create({ data: { worldId: world.id, categoryId: parent.id, title: "B", slug: "b", order: 1 } });
  const send = (method: string, body: object) => authenticatedFetch(`${origin}/api/categories`, { method, headers: { "Content-Type": "application/json" }, body: JSON.stringify({ worldId: world.id, ...body }) });
  assert.equal((await send("PATCH", { action: "moveCategory", id: parent.id, parentId: child.id })).status, 400);
  assert.equal((await send("PATCH", { action: "moveArticle", id: first.id, parentId: foreign.id })).status, 400);
  assert.equal((await send("POST", { name: "", parentId: null })).status, 400);
  assert.equal((await send("POST", { name: "Invalid", parentId: foreign.id })).status, 400);
  assert.equal((await send("PATCH", { action: "moveArticle", id: second.id, parentId: parent.id, beforeId: first.id })).status, 200);
  assert.deepEqual((await db.article.findMany({ where: { categoryId: parent.id }, orderBy: { order: "asc" } })).map(article => article.id), [second.id, first.id]);
  const created = await send("POST", { name: "Guilds", parentId: child.id });
  assert.equal(created.status, 201);
  const guild = await created.json();
  assert.equal((await send("PATCH", { action: "rename", id: guild.id, name: "Factions" })).status, 200);
  assert.equal((await send("PATCH", { action: "moveCategory", id: guild.id, parentId: null, beforeId: parent.id })).status, 200);
  assert.equal((await db.category.findUniqueOrThrow({ where: { id: guild.id } })).order, 0);
  assert.equal((await send("DELETE", { id: parent.id })).status, 200);
  assert.equal((await db.category.findUniqueOrThrow({ where: { id: child.id } })).parentId, null);
  assert.equal((await db.article.findUniqueOrThrow({ where: { id: first.id } })).categoryId, null);
  assert.equal((await db.article.findUniqueOrThrow({ where: { id: second.id } })).categoryId, null);
  assert.equal(await db.article.count({ where: { worldId: world.id } }), 2);
  assert.equal((await db.category.findUniqueOrThrow({ where: { id: foreign.id } })).worldId, otherWorld.id);
});
